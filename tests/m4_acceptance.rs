/// Drive `tick` until `predicate` returns true on the accumulated
/// per-process events, or the deadline elapses. Returns whatever
/// has been accumulated.
fn drain_until<F: Fn(&[ProcessEvent]) -> bool>(
    sup: &mut ProcessSupervisor,
    id: ProcessId,
    deadline: Duration,
    predicate: F,
) -> Vec<ProcessEvent> {
    let stop = Instant::now() + deadline;
    let mut all = Vec::new();
    while Instant::now() < stop {
        sup.tick();
        let mut evs = sup.take_events(id);
        all.append(&mut evs);
        if predicate(&all) {
            return all;
        }
        std::thread::sleep(Duration::from_millis(10));
    }
    all
}

fn has_exit_event(events: &[ProcessEvent]) -> bool {
    events.iter().any(|e| {
        matches!(
            e.kind,
            ProcessEventKind::Exited { .. }
                | ProcessEventKind::Signaled { .. }
                | ProcessEventKind::Crashed { .. }
        )
    })
}

