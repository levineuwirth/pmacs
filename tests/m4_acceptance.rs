/// Helper: scan PATH for a binary by name. Returns the absolute
/// path if found.
fn which_binary(name: &str) -> std::io::Result<std::path::PathBuf> {
    let path = std::env::var_os("PATH")
        .ok_or_else(|| std::io::Error::new(std::io::ErrorKind::NotFound, "PATH unset"))?;
    for dir in std::env::split_paths(&path) {
        let candidate = dir.join(name);
        if candidate.is_file() {
            return Ok(candidate);
        }
    }
    Err(std::io::Error::new(
        std::io::ErrorKind::NotFound,
        format!("{name} not on PATH"),
    ))
}

