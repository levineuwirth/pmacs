/// Acceptance (1/3): a `textDocument/definition` request round-trips
/// through the manager and lands in the definition store as a parsed
/// `Location` list.
#[test]
fn m4_12_definition_response_lands_in_store() {
    let (sup, mgr) = make_lsp_test_manager();
    let sid = mgr.borrow_mut().spawn(fake_spec("def")).expect("spawn");
    let _ = drain_lsp_until(&sup, &mgr, sid, Duration::from_secs(5), |evs| {
        evs.iter()
            .any(|e| matches!(e.kind, LspEventKind::Initialized { .. }))
    });
    let uri = "file:///tmp/m4_12_def.rs";
    mgr.borrow_mut()
        .did_open(sid, uri, 1, "fn foo() { bar(); }\n")
        .expect("didOpen");
    let _ = mgr
        .borrow_mut()
        .request_definition(sid, uri, 0, 12)
        .expect("request_definition");

    let key = DefinitionKey::new(sid.raw().to_string(), uri.to_owned());
    let deadline = Instant::now() + Duration::from_secs(2);
    let mut got: Option<(u32, u32)> = None;
    while Instant::now() < deadline {
        sup.borrow_mut().tick();
        mgr.borrow_mut().tick();
        let store = mgr.borrow().definition_store();
        let guard = store.lock().expect("lock");
        if let Some(r) = guard.get(&key) {
            if let Some(loc) = r.locations.first() {
                got = Some((loc.line, loc.col));
                break;
            }
        }
        drop(guard);
        std::thread::sleep(Duration::from_millis(15));
    }
    let (line, col) = got.expect("expected a definition location");
    assert_eq!((line, col), (7, 4), "fake LSP returns line=7 col=4");
    let _ = mgr.borrow_mut().stop(sid);
}

