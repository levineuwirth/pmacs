/// Drain LSP events until `pred` is satisfied or the deadline lapses.
/// Ticks the process supervisor first so reader-thread output lands
/// in the LSP layer's stdout buffer in time for frame parsing.
fn drain_lsp_until<F: Fn(&[LspEvent]) -> bool>(
    sup: &pmacs::lua_bindings::SharedProcessSupervisor,
    mgr: &pmacs::lsp::SharedLspManager,
    sid: LspServerId,
    deadline: Duration,
    pred: F,
) -> Vec<LspEvent> {
    let stop = Instant::now() + deadline;
    let mut all: Vec<LspEvent> = Vec::new();
    while Instant::now() < stop {
        sup.borrow_mut().tick();
        mgr.borrow_mut().tick();
        let mut evs = mgr.borrow_mut().take_events(sid);
        all.append(&mut evs);
        if pred(&all) {
            return all;
        }
        std::thread::sleep(Duration::from_millis(15));
    }
    all
}

