/// Synthetic Rust source: `n` lines of plausible-but-trivial code.
/// Each line is short enough that the file is ~30--35 KB at 5000
/// lines --- representative of the 5000-line files Pmacs is meant
/// to feel snappy on.
fn synthetic_rust_source(n: usize) -> Vec<u8> {
    let mut out = String::with_capacity(n * 64);
    out.push_str("// generated by m4_acceptance::synthetic_rust_source\n");
    out.push_str("use std::sync::Arc;\n\n");
    for i in 0..n {
        writeln!(
            out,
            "pub fn fn_{i:05}(x: u32) -> u32 {{ let y = x + {i}; y * 2 }}"
        )
        .expect("write into String can't fail");
    }
    out.into_bytes()
}

/// Cold parse of a 5000-line synthetic Rust file completes in under
/// 100 ms. The acceptance criterion measures the parse duration
/// itself, not the dispatch round-trip. Run under `--release` ---
/// debug builds disable the optimizations tree-sitter relies on.
#[test]
#[ignore = "perf gate; requires release build"]
fn m4_1_initial_parse_of_5000_line_file_under_100ms() {
    let source = synthetic_rust_source(5000);
    let req = ParseRequest {
        source: Arc::from(source),
        language: tree_sitter_rust::LANGUAGE.into(),
        language_name: "rust".to_owned(),
        prior_tree: None,
        edits: Vec::new(),
    };
    let bundle = syntax::run_parse(req).expect("parse succeeds");
    assert_eq!(bundle.tree.root_node().kind(), "source_file");
    assert!(
        bundle.parse_duration < Duration::from_millis(100),
        "5000-line cold parse took {:?}, exceeds 100 ms budget",
        bundle.parse_duration
    );
}

/// Incremental parse following a single-character edit completes in
/// under 5 ms. The acceptance criterion is meant to capture the
/// "edit-and-go" cost the user pays on every keystroke once
/// tree-sitter is wired into M4's display path. Run under
/// `--release`.
#[test]
#[ignore = "perf gate; requires release build"]
fn m4_1_incremental_parse_under_5ms() {
    // Build buffer + ParseView, do a cold parse, then make a
    // single-byte edit and re-parse with the accumulated InputEdit.
    let mut buf = Buffer::new(BufferId::next(), "scratch.rs");
    let source = synthetic_rust_source(5000);
    buf.apply_edit(EditOp::Insert {
        pos: 0,
        bytes: &source,
    })
    .unwrap();
    let view = ParseView::new(&buf, tree_sitter_rust::LANGUAGE.into(), "rust".to_owned());
    let handle = view.handle();
    buf.attach_view(Box::new(view));

    // Cold parse to populate the prior tree. Doesn't count toward
    // the 5 ms budget --- this is the "after the user opens the file"
    // state.
    let cold_req = handle.make_request();
    let cold_bundle = syntax::run_parse(cold_req).expect("cold parse");
    handle.install(Arc::new(cold_bundle));

    // One incremental edit. Insert a single space inside the body
    // of `fn_00010` --- a real edit a user might make. The exact
    // location is computed from the line layout: line k (0-based)
    // for `fn_{k:05}` definitions starts after the 3-line prologue
    // (use std::sync::Arc, blank line, comment), each subsequent
    // line is exactly the same length, and we pick a byte inside
    // line 14 (i.e., fn_00010) to insert at.
    let target_line: usize = 14;
    // Find the byte offset of the start of `target_line` in the
    // current source. We use the bundle's installed source, which
    // matches what was parsed.
    let cur_source: Vec<u8> = handle.source_snapshot();
    let mut nl_count = 0usize;
    let mut target_offset = cur_source.len();
    for (i, b) in cur_source.iter().enumerate() {
        if *b == b'\n' {
            nl_count += 1;
            if nl_count == target_line {
                target_offset = i + 1;
                break;
            }
        }
    }
    // Insert 1 byte (a space) somewhere inside the chosen line ---
    // pick column 25 if the line is long enough, otherwise the
    // start.
    let line_end = cur_source[target_offset..]
        .iter()
        .position(|b| *b == b'\n')
        .map_or(cur_source.len(), |p| target_offset + p);
    let insert_at = (target_offset + 25).min(line_end);

    buf.apply_edit(EditOp::Insert {
        pos: insert_at as u64,
        bytes: b" ",
    })
    .unwrap();
    assert_eq!(handle.pending_edit_count(), 1);

    let req = handle.make_request();
    let bundle = syntax::run_parse(req).expect("incremental parse");
    assert_eq!(bundle.tree.root_node().kind(), "source_file");
    assert!(
        bundle.parse_duration < Duration::from_millis(5),
        "incremental parse took {:?}, exceeds 5 ms budget",
        bundle.parse_duration
    );
}

/// The parse-on-worker path: dispatch through `AsyncRuntime`,
/// observe settle, drain the bundle from the side handoff. This
/// exercises the *full* T M4.1 dispatch shape (vs the synchronous
/// `run_parse` that the perf gates use), and demonstrates that the
/// "Parse runs on a worker" task description is satisfied.
#[test]
fn m4_1_dispatch_parse_round_trips_via_runtime() {
    let rt = AsyncRuntime::with_pool_size(1);
    let req = ParseRequest {
        source: Arc::from(synthetic_rust_source(200)),
        language: tree_sitter_rust::LANGUAGE.into(),
        language_name: "rust".to_owned(),
        prior_tree: None,
        edits: Vec::new(),
    };
    let id = rt.dispatch_parse(req, None);
    let deadline = Instant::now() + Duration::from_secs(5);
    while !rt.is_complete(id) {
        assert!(Instant::now() < deadline, "parse settle deadline");
        let _ = rt.tick();
        std::thread::sleep(Duration::from_millis(1));
    }
    let bundle = rt
        .take_parse_tree(id)
        .expect("parse handoff holds bundle on Complete");
    match rt.take_result(id) {
        Some(JobOutcome::Complete(JobResult::Parse { duration_ms })) => {
            assert!(duration_ms < 100, "200-line parse should be quick");
        }
        other => panic!("unexpected outcome: {other:?}"),
    }
    assert_eq!(bundle.tree.root_node().kind(), "source_file");
    assert_eq!(bundle.language_name, "rust");
}

/// The Lua introspection criterion: walking the parse tree from a
/// Lua script returns the same shape we'd get from the Rust API.
/// Driven through `pmacs.parse._parse_now` so the test doesn't have
/// to drive the async settle path from Lua.
#[test]
fn m4_1_parse_tree_introspectable_via_lua() {
    use pmacs::editor::EditorState;
    use pmacs::lua_bindings::BufferIdLua;

    let editor = EditorState::new();
    // Insert a buffer with known shape; bind its handle into Lua as
    // `BUF` so the script can reference it by name.
    let buf_id = editor
        .lua_host
        .registry()
        .borrow_mut()
        .create_from_bytes("scratch.rs".to_owned(), b"fn main() { let x = 1 + 2; }\n");
    editor
        .lua_host
        .lua()
        .globals()
        .set("BUF", BufferIdLua(buf_id))
        .expect("set BUF");

    let script = r#"
        local tree = pmacs.parse._parse_now(BUF, "rust")
        assert(tree, "tree must be returned")
        assert(tree:language() == "rust", "language label")
        local root = tree:root()
        assert(root, "root node")
        assert(root:type() == "source_file", "root type: " .. tostring(root:type()))
        assert(root:has_error() == false, "no parse errors")
        assert(root:start_byte() == 0, "root starts at 0")
        local children = root:named_children()
        assert(#children >= 1, "at least one named child")
        local fn_node = children[1]
        assert(fn_node:type() == "function_item",
            "first named child must be function_item, got " .. tostring(fn_node:type()))
        local same = pmacs.parse.tree(BUF)
        assert(same, "pmacs.parse.tree returns the installed bundle")
        assert(same:root():type() == "source_file", "round-trip via tree() preserves shape")
        return true
    "#;
    let ok: bool = editor
        .lua_host
        .lua()
        .load(script)
        .eval()
        .expect("Lua introspection");
    assert!(ok);
}

