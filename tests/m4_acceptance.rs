/// Drive `EditorState::tick_async` until `predicate` returns `true`.
/// Inlined here because the editor's own `pump_async` lives inside
/// `editor::tests` and isn't exposed publicly.
fn pump_async<F: Fn(&pmacs::editor::EditorState) -> bool>(
    state: &mut pmacs::editor::EditorState,
    predicate: F,
) {
    let deadline = Instant::now() + Duration::from_secs(2);
    while !predicate(state) {
        assert!(Instant::now() < deadline, "async pump deadline exceeded");
        state.tick_async();
        std::thread::sleep(Duration::from_millis(2));
    }
}

/// Returns the language label of the parse tree currently installed
/// for the active buffer, or `None` if no parse has settled yet.
fn current_tree_language(state: &pmacs::editor::EditorState) -> Option<String> {
    let lua = state.lua_host.lua();
    let chunk = r"
        local buf = pmacs.window.buffer()
        if not buf then return nil end
        local tree = pmacs.parse.tree(buf)
        if not tree then return nil end
        return tree:language()
    ";
    lua.load(chunk).eval::<Option<String>>().ok().flatten()
}

/// Opening a `.rs` file produces a parse tree whose root is a
/// `source_file` and whose language label is `rust`. The dispatch
/// runs through the `buffer.after-load` hook installed by
/// `builtin/runtime/syntax.lua`, the worker pool, and the per-tick
/// settle path that drains the parse handoff.
#[test]
fn m4_2_opening_a_rust_file_produces_a_parse_tree() {
    let dir = tempfile::tempdir().expect("tempdir");
    let path = dir.path().join("hello.rs");
    std::fs::write(&path, b"fn main() { let x = 1 + 2; }\n").expect("write");

    let mut state = pmacs::editor::EditorState::open(path).expect("open .rs");
    pump_async(&mut state, |s| current_tree_language(s).is_some());
    assert_eq!(current_tree_language(&state).as_deref(), Some("rust"));

    // Verify the tree's root is the expected language node, not just
    // some installed-but-empty bundle.
    let root_kind: String = state
        .lua_host
        .lua()
        .load(
            r"
            local buf = pmacs.window.buffer()
            return pmacs.parse.tree(buf):root():type()
        ",
        )
        .eval()
        .expect("root type");
    assert_eq!(root_kind, "source_file");
}

