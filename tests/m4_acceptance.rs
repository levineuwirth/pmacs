/// Acceptance (3/3): Lua surface drives both new request paths and
/// reads back the parsed responses without touching the Rust manager
/// directly. Validates `pmacs.lsp.request_definition`,
/// `pmacs.lsp.request_formatting`, `pmacs.definition.locations`, and
/// `pmacs.formatting.edits`.
#[test]
#[allow(
    clippy::too_many_lines,
    reason = "linear test body covers spawn → init → did_open → request → poll → assert"
)]
fn m4_12_lua_surface_drives_definition_and_formatting() {
    use pmacs::editor::EditorState;

    let mut s = EditorState::new();
    let fake = fake_lsp_path();

    // Spawn a server through the Lua surface.
    let sid_repr: String = s
        .lua_host
        .lua()
        .load(format!(
            "
            local id = pmacs.lsp.spawn {{
                label = 'lua-m4-12',
                language_id = 'rust',
                command = '{fake}',
            }}
            return tostring(id)
            "
        ))
        .eval()
        .expect("spawn via lua");
    assert!(sid_repr.starts_with("LspServerId"), "got {sid_repr:?}");

    // Drain until initialized.
    let deadline = Instant::now() + Duration::from_secs(5);
    while Instant::now() < deadline {
        s.tick_processes();
        s.tick_lsp();
        let initialized: bool = s
            .lua_host
            .lua()
            .load(
                "
                local servers = pmacs.lsp.list()
                for _, info in ipairs(servers) do
                    if info.state and info.state.kind == 'initialized' then return true end
                end
                return false
                ",
            )
            .eval()
            .unwrap();
        if initialized {
            break;
        }
        std::thread::sleep(Duration::from_millis(20));
    }

    let uri = "file:///tmp/m4_12_lua.rs";
    s.lua_host
        .lua()
        .load(format!(
            "
            local target
            for _, info in ipairs(pmacs.lsp.list()) do
                target = info.id; break
            end
            pmacs.lsp.did_open(target, '{uri}', 1, 'fn main() {{ helper(); }}\\n')
            pmacs.lsp.request_definition(target, '{uri}', 0, 13)
            pmacs.lsp.request_formatting(target, '{uri}', 4, true)
            "
        ))
        .exec()
        .expect("kick off lua-side requests");

    // Drain until both responses have populated their stores.
    let deadline = Instant::now() + Duration::from_secs(5);
    let mut have_def = false;
    let mut have_fmt = false;
    while Instant::now() < deadline && (!have_def || !have_fmt) {
        s.tick_processes();
        s.tick_lsp();
        let result: (bool, bool) = s
            .lua_host
            .lua()
            .load(format!(
                "
                local target
                for _, info in ipairs(pmacs.lsp.list()) do
                    target = info.id; break
                end
                local locs = pmacs.definition.locations(target, '{uri}')
                local edits = pmacs.formatting.edits(target, '{uri}')
                return #locs > 0, #edits > 0
                "
            ))
            .eval()
            .unwrap();
        have_def = result.0;
        have_fmt = result.1;
        if !have_def || !have_fmt {
            std::thread::sleep(Duration::from_millis(20));
        }
    }
    assert!(have_def, "definition response did not land in the store");
    assert!(have_fmt, "formatting response did not land in the store");

    // Spot-check field shapes.
    let (line, col, fmt_count, fmt_first_text): (u32, u32, usize, String) = s
        .lua_host
        .lua()
        .load(format!(
            "
            local target
            for _, info in ipairs(pmacs.lsp.list()) do
                target = info.id; break
            end
            local locs = pmacs.definition.locations(target, '{uri}')
            local edits = pmacs.formatting.edits(target, '{uri}')
            return locs[1].line, locs[1].col, #edits, edits[1].new_text
            "
        ))
        .eval()
        .expect("read fields back");
    assert_eq!((line, col), (7, 4));
    assert_eq!(fmt_count, 2);
    assert_eq!(fmt_first_text, "");
}

