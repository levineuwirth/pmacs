/// No zombies: dropping the supervisor SIGTERMs every running
/// child, then SIGKILLs after the grace period. After Drop, the
/// pid must be reaped (kill(pid, 0) returns ESRCH).
#[test]
fn m4_4_no_zombies_after_editor_drop() {
    use nix::unistd::Pid;
    let pid: u32 = {
        let mut sup = ProcessSupervisor::new();
        sup.set_grace_period(Duration::from_millis(200));
        let mut spec = ProcessSpec::new("zombie-test", "/bin/sh");
        spec.args = vec!["-c".into(), "sleep 60".into()];
        let id = sup.spawn(spec).expect("spawn");
        let _ = drain_until(&mut sup, id, Duration::from_secs(2), |evs| {
            evs.iter()
                .any(|e| matches!(e.kind, ProcessEventKind::Started { .. }))
        });
        let ProcessState::Running { pid, .. } = sup.state(id).cloned().unwrap() else {
            panic!("expected Running");
        };
        pid
    };
    // sup is dropped at the end of the block above; shutdown
    // SIGTERMs + SIGKILLs the child.
    let nix_pid = Pid::from_raw(i32::try_from(pid).unwrap());
    let dead = || {
        matches!(
            nix::sys::signal::kill(nix_pid, None),
            Err(nix::errno::Errno::ESRCH)
        )
    };
    let deadline = Instant::now() + Duration::from_secs(2);
    while !dead() && Instant::now() < deadline {
        std::thread::sleep(Duration::from_millis(20));
    }
    assert!(
        dead(),
        "child pid {pid} must be reaped/dead after supervisor Drop"
    );
}

