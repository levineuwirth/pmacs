//! Acceptance gates for Milestone 4.
//!
//! Per the spec, every M4.x acceptance bullet has an automated
//! regression test.
//!
//! # T M4.1 --- Tree-sitter integration
//!
//! 1. Initial parse of a 5000-line file under 100 ms →
//!    `m4_1_initial_parse_of_5000_line_file_under_100ms`.
//! 2. Incremental parse on edit under 5 ms →
//!    `m4_1_incremental_parse_under_5ms`.
//! 3. Parse tree introspectable via Lua →
//!    `m4_1_parse_tree_introspectable_via_lua`.
//!
//! # T M4.2 --- Rust and Lua grammars wired up
//!
//! 1. Opening a `.rs` or `.lua` file produces a parse tree →
//!    `m4_2_opening_a_rust_file_produces_a_parse_tree`,
//!    `m4_2_opening_a_lua_file_produces_a_parse_tree`.
//! 2. Adding a new grammar requires only a config entry →
//!    `m4_2_register_extension_attaches_for_a_runtime_added_extension`.
//!
//! # T M4.3 --- Syntax-highlight view
//!
//! 1. Rust file opens with full syntax highlighting under 100 ms →
//!    `m4_3_open_rust_file_highlights_under_100ms` (release-gated).
//! 2. Highlight updates on edit within one frame after parse
//!    completes → `m4_3_highlight_updates_within_one_frame_after_parse`.
//! 3. Theming via Lua-defined color schemes →
//!    `m4_3_theming_via_lua_color_scheme`.
//!
//! # T M4.4 --- Process supervisor
//!
//! 1. Process lifecycle correctly handled (spawn, exit, signal,
//!    crash) → `m4_4_lifecycle_spawn_and_exit`,
//!    `m4_4_lifecycle_signal_terminates`,
//!    `m4_4_lifecycle_crash_surfaces_as_event`.
//! 2. Restart policy honored →
//!    `m4_4_restart_policy_on_crash_respawns`,
//!    `m4_4_restart_policy_never_does_not_respawn`.
//! 3. No zombie processes after editor exit →
//!    `m4_4_no_zombies_after_editor_drop`.
//! 4. PTY mode works for terminal-aware children →
//!    `m4_4_pty_mode_child_observes_a_tty`.
//!
//! # T M4.5 --- LSP client core
//!
//! 1. `rust-analyzer` connects, initializes, and reports
//!    capabilities → `m4_5_rust_analyzer_initializes` (gated on the
//!    binary being on PATH; skipped silently otherwise).
//! 2. `didChange` notifications sent on edit →
//!    `m4_5_did_change_notifications_go_out_after_edits`.
//! 3. Server crash auto-restarts; surfaced in status indicator →
//!    `m4_5_server_crash_auto_restarts`.
//! 4. Protocol violations on either side surface as structured
//!    errors → `m4_5_protocol_violation_surfaces_as_structured_error`.
//!
//! # T M4.6 --- LSP-backed views: diagnostics
//!
//! 1. Diagnostics update within 500 ms of last keystroke →
//!    `m4_6_diagnostics_arrive_within_500ms`.
//! 2. Navigate-to-next-diagnostic command works →
//!    `m4_6_navigate_next_diagnostic_wraps`.
//! 3. Diagnostic source visible →
//!    `m4_6_diagnostic_source_field_is_preserved`.
//!
//! The non-rust-analyzer M4.5 tests run a tiny shell-script "echo
//! LSP" peer (`fake_lsp_server.sh`) that speaks just enough of the
//! protocol to exercise the framing, lifecycle, and dispatcher
//! without depending on a real language server being installed.
//!
//! Run with:
//!
//! ```sh
//! cargo test --test m4_acceptance
//! cargo test --release --test m4_acceptance -- --ignored --nocapture
//! ```
//!
//! Perf gates in M4.1 ((1) and (2)) and M4.3 (1) are `#[ignore]`'d
