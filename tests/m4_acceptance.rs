/// "Adding a new grammar requires only a config entry." The
/// long-form test of this is the existence of the rust + lua entries
/// in `crate::syntax::BUILTIN_LANGUAGES`. The short-form test:
/// `register_extension` (the runtime equivalent of adding a
/// non-builtin entry) attaches a parse view by extension without any
/// extra wiring. We map a `.myrust` extension to the existing `rust`
/// grammar and verify the auto-attach hook picks it up.
#[test]
fn m4_2_register_extension_attaches_for_a_runtime_added_extension() {
    let dir = tempfile::tempdir().expect("tempdir");
    let path = dir.path().join("hello.myrust");
    std::fs::write(&path, b"fn main() {}\n").expect("write");

    let mut state = pmacs::editor::EditorState::open(path).expect("open .myrust");
    // The auto-attach hook fires *during* open, but at that point our
    // custom extension isn't registered yet --- so the first hook
    // invocation is a no-op. Register the extension and trigger the
    // hook again by re-parsing the active buffer through Lua.
    state.syntax_registry.register_extension("myrust", "rust");
    state
        .lua_host
        .lua()
        .load(
            r"
            local buf = pmacs.window.buffer()
            local lang = pmacs.parse.language_for_path(buf:name())
            assert(lang == 'rust', 'expected rust, got ' .. tostring(lang))
            pmacs.parse._dispatch(buf, lang)
        ",
        )
        .exec()
        .expect("dispatch via registered extension");
    pump_async(&mut state, |s| current_tree_language(s).is_some());
    assert_eq!(current_tree_language(&state).as_deref(), Some("rust"));
}

/// Sanity check on the config table itself: both bundled grammars
/// resolve their canonical extensions, and the lookup is
/// case-sensitive (matches conventional Unix filename handling).
#[test]
fn m4_2_builtin_languages_resolve_canonical_extensions() {
    let registry = pmacs::syntax::SyntaxRegistry::new();
    assert_eq!(registry.language_name_for_extension("rs"), Some("rust"));
    assert_eq!(registry.language_name_for_extension("lua"), Some("lua"));
    assert!(registry.language_name_for_extension("RS").is_none());
    assert!(registry.language_name_for_extension("txt").is_none());
    assert_eq!(
        registry
            .language_name_for_path("/tmp/foo/bar.rs")
            .as_deref(),
        Some("rust")
    );
    assert_eq!(
        registry.language_name_for_path("foo.lua").as_deref(),
        Some("lua")
    );
    assert!(registry.language_name_for_path("README").is_none());
}

